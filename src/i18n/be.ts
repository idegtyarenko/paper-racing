// Беларуская лакаль (афіцыйны правапіс, «на ты»). Форма — з en.ts (тып Strings).
// Неразрыўныя прабелы ( ) расстаўляе scripts/typography.mjs (правіла кароткіх слоў
// пашырана на «і», «ў») і апострафы (’) — не праў іх уручную, гані `npm run typo`.

import type { Strings } from './en';

/** Беларускі парадкавы лічэбнік, мужчынскі род: 1-ы, 2-і, 3-і, 4-ы, 5-ы…
 *  На «-і» канчаюцца толькі «другі» і «трэці», але не «дванаццаты»/«трынаццаты». */
function ordinalM(n: number): string {
  const rem100 = n % 100;
  if (rem100 >= 11 && rem100 <= 13) return `${n}-ы`;
  const rem10 = n % 10;
  return rem10 === 2 || rem10 === 3 ? `${n}-і` : `${n}-ы`;
}

